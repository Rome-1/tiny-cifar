"""How many bytes of DSP does a keyword spotter need?

This is the question that decides whether Speech Commands can have a
sub-kilobyte artifact at all. On CIFAR-10 the input transform is free: an 8x8
RGB block mean is one reshape and one `.mean`, about thirty source bytes, and it
stores nothing. Audio is not obviously so. A log-mel front end needs framing, a
window, an FFT, a filterbank and a log, and every one of those is either source
bytes or -- worse -- a stored coefficient table that counts as weight.

Each candidate below is measured as a **complete, runnable artifact**: it
computes its features and returns a label. The classifier is deliberately
degenerate (`argmax` of the feature vector, modulo the class count), so the
number this script reports is the floor -- what the front end costs before any
model exists. `delta` subtracts the `null` row, which is the same artifact with
the DSP removed, and so isolates the DSP from the fixed cost of being a Python
artifact at all.

Every row is checked three ways before its bytes are believed:

  * it passes `artifact.check_imports` (numpy only);
  * it runs in the harness sandbox on real waveforms via
    `tinycifar.evaluate_nclass`, so a fragment that does not actually execute
    cannot post a byte count;
  * its feature count and dtype are printed, so a "cheap" extractor that
    silently produces one number per clip is visible as such.

Run:
    python3 experiments/kws_prep.py --out data/sc12.npz
    python3 experiments/kws_extractors.py
"""

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from tinycifar import artifact as A  # noqa: E402
from tinycifar.evaluate_nclass import evaluate_arrays  # noqa: E402

# --------------------------------------------------------------------------
# the candidates
#
# Each is a numpy expression over `x` (int16 [N, 16000]) binding `v` to a
# float feature matrix [N, D]. Written as it would ship: golfed, no spaces that
# do not have to be there, no intermediate names that are used once.
#
# `stored` records whether the extractor ships any coefficient the decoder
# cannot regenerate -- the crux. A stored mel matrix at 20 bands x 251 bins is
# 5,020 numbers, which at even one byte each is five times the whole budget.
# --------------------------------------------------------------------------

EXTRACTORS: list[tuple[str, str, str, bool]] = [
    (
        "null",
        "no DSP at all -- the fixed cost of being an artifact",
        "v=x[:,:12]*1.",
        False,
    ),
    (
        "sub64",
        "raw waveform block-averaged to 64 samples",
        "v=x.reshape(len(x),64,250).mean(2)",
        False,
    ),
    (
        "env64",
        "rectified envelope, 64 frames",
        "v=abs(x*1.).reshape(len(x),64,250).mean(2)",
        False,
    ),
    (
        "env32x1",
        "log rectified envelope, 32 frames",
        "v=np.log1p(abs(x*1.).reshape(len(x),32,500).mean(2))",
        False,
    ),
    (
        "zcr32",
        "zero-crossing rate + envelope, 32 frames each",
        "a=x.reshape(len(x),32,500)*1.;v=np.c_[abs(np.diff(np.sign(a))).mean(2),"
        "np.log1p(abs(a).mean(2))]",
        False,
    ),
    (
        "haar",
        "Haar packet: dyadic band energies per frame, no trig table",
        "a=x[:,:15872].reshape(len(x),31,512)*1.;v=[]\n"
        " while a.shape[2]>1:\n"
        "  b=a.reshape(len(x),31,-1,2);a=b[...,0]+b[...,1];"
        "v+=[np.log1p(abs(b[...,0]-b[...,1]).mean(2))]\n"
        " v=np.concatenate(v,1)",
        False,
    ),
    (
        "fft-spec",
        "full rfft magnitude spectrogram, 32 frames x 251 bins",
        "v=abs(np.fft.rfft(x.reshape(len(x),32,500)*1.)).reshape(len(x),-1)",
        False,
    ),
    (
        "fft-oct",
        "rfft into 20 octave-spaced bands, log -- edges generated, not stored",
        "v=np.log1p(np.add.reduceat(abs(np.fft.rfft(x.reshape(len(x),32,500)*1.)),"
        "(2**np.linspace(0,7.97,20)).astype(int),2)).reshape(len(x),-1)",
        False,
    ),
    (
        "fft-mel",
        "rfft into 20 true-mel bands, log -- mel edges generated by formula",
        "v=np.log1p(np.add.reduceat(abs(np.fft.rfft(x.reshape(len(x),32,500)*1.)),"
        "(21.9*(10**(np.linspace(0,3.08,20)/2595)-1)).astype(int),2))"
        ".reshape(len(x),-1)",
        False,
    ),
    (
        "fft-mel-han",
        "fft-mel with a Hann window, generated by cos()",
        "v=np.log1p(np.add.reduceat(abs(np.fft.rfft(x.reshape(len(x),32,500)"
        "*(1-np.cos(np.arange(500)/79.6)))),"
        "(21.9*(10**(np.linspace(0,3.08,20)/2595)-1)).astype(int),2))"
        ".reshape(len(x),-1)",
        False,
    ),
    (
        "mfcc",
        "fft-mel then a DCT-by-rfft cepstrum, 10 coefficients per frame",
        "v=abs(np.fft.rfft(np.log1p(np.add.reduceat(abs(np.fft.rfft("
        "x.reshape(len(x),32,500)*1.)),"
        "(21.9*(10**(np.linspace(0,3.08,20)/2595)-1)).astype(int),2))))"
        "[:,:,:10].reshape(len(x),-1)",
        False,
    ),
    (
        "fft-mel-stored",
        "fft-mel with the band edges SHIPPED as bytes instead of generated",
        None,   # built specially: carries a weight file
        True,
    ),
    (
        "mel-matrix",
        "the textbook front end: a real 20x251 triangular filterbank, shipped",
        ...,    # built specially: carries the matrix
        True,
    ),
]

# A complete artifact: the extractor, then a classifier so degenerate it cannot
# be confused for one. `%12` keeps the label in range for any feature width.
TEMPLATE = """import numpy as np
def predict(x):
 {FEAT}
 return v.argmax(1)%12
"""

# The stored-coefficient control. Same extractor as `fft-mel`, but the twenty
# band edges arrive as a file rather than from the formula, which is the version
# an off-the-shelf mel front end would ship.
TEMPLATE_STORED = """import numpy as np
E=np.frombuffer(open(__file__[:-10]+"w","rb").read(),np.uint8)*1
def predict(x):
 v=np.log1p(np.add.reduceat(abs(np.fft.rfft(x.reshape(len(x),32,500)*1.)),E,2)).reshape(len(x),-1)
 return v.argmax(1)%12
"""

# A full triangular mel filterbank over the 251 rfft bins, as `librosa.filters.mel`
# or `torchaudio.MelScale` would build it. This row exists to show the kill
# criterion can fire: it is the same features as `fft-mel`, but the filterbank
# arrives as data rather than from a formula.
TEMPLATE_MATRIX = """import numpy as np
M=np.frombuffer(open(__file__[:-10]+"w","rb").read(),np.float16).reshape(251,20)
def predict(x):
 v=np.log1p(abs(np.fft.rfft(x.reshape(len(x),32,500)*1.))@M).reshape(len(x),-1)
 return v.argmax(1)%12
"""


def mel_matrix() -> np.ndarray:
    """251 rfft bins x 20 triangular mel bands, unit-height."""
    hz = np.arange(251) * 16000 / 500
    mel = 2595 * np.log10(1 + hz / 700)
    edges = np.linspace(0, 2595 * np.log10(1 + 8000 / 700), 22)
    m = np.zeros((251, 20), dtype=np.float32)
    for j in range(20):
        lo, mid, hi = edges[j], edges[j + 1], edges[j + 2]
        left = (mel - lo) / (mid - lo)
        right = (hi - mel) / (hi - mid)
        m[:, j] = np.clip(np.minimum(left, right), 0, None)
    return m


MEL_EDGES = (21.9 * (10 ** (np.linspace(0, 3.08, 20) / 2595) - 1)).astype(int)

_STORED_EXPR = ("v=np.log1p(np.add.reduceat(abs(np.fft.rfft("
                "x.reshape(len(x),32,500)*1.)),E,2)).reshape(len(x),-1)")
_MATRIX_EXPR = ("v=np.log1p(abs(np.fft.rfft(x.reshape(len(x),32,500)*1.))@M)"
                ".reshape(len(x),-1)")


def build(name: str, expr) -> dict[str, bytes]:
    if expr is None:
        return {"predict.py": TEMPLATE_STORED.encode(),
                "w": MEL_EDGES.astype(np.uint8).tobytes()}
    if expr is ...:
        return {"predict.py": TEMPLATE_MATRIX.encode(),
                "w": mel_matrix().astype(np.float16).tobytes()}
    return {"predict.py": TEMPLATE.format(FEAT=expr).encode()}


def feature_shape(expr, x: np.ndarray) -> tuple[int, str]:
    """Run the fragment locally to see how wide it really is."""
    if expr is None:
        expr = _STORED_EXPR
    elif expr is ...:
        expr = _MATRIX_EXPR
    ns = {"np": np, "x": x, "E": MEL_EDGES, "M": mel_matrix().astype(np.float16)}
    exec("def _f(x,np=np,E=E,M=M):\n " + expr + "\n return v", ns)   # noqa: S102
    v = ns["_f"](x)
    return int(v.shape[1]), str(v.dtype)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", default=str(REPO / "data" / "sc12.npz"))
    ap.add_argument("--n", type=int, default=600,
                    help="waveforms used only to prove each fragment executes")
    a = ap.parse_args(argv)

    z = np.load(a.data)
    x, y = z["xtest"][: a.n], z["ytest"][: a.n]
    print(f"{len(x)} waveforms {x.shape[1:]} {x.dtype} for the execution check\n")

    rows = []
    null_bytes = None
    for name, note, expr, stored in EXTRACTORS:
        files = build(name, expr)
        viol = A.check_imports(files)
        if viol:
            raise RuntimeError(f"{name}: {viol}")
        size = A.measure(files)
        d, dt = feature_shape(expr, x)

        with tempfile.TemporaryDirectory() as td:
            A.write_dir(files, td)
            rec = evaluate_arrays(td, x, y, 12, name=name, split="test")
        if rec["description_length"] != size.description_length:
            raise RuntimeError(f"{name}: size disagreement")

        if null_bytes is None:
            null_bytes = size.description_length
        rows.append((name, note, size, d, dt, stored,
                     size.description_length - null_bytes,
                     len(files.get("w", b"")), len(files["predict.py"])))

    print(f"{'extractor':<16}{'bytes':>8}{'delta':>8}{'src B':>7}{'coef B':>8}"
          f"{'dims':>7}  stored?  description")
    print("-" * 118)
    for name, note, size, d, dt, stored, delta, wb, sb in rows:
        print(f"{name:<16}{size.description_length:>8,}{delta:>+8,}{sb:>7}"
              f"{wb:>8,}{d:>7}  {'YES' if stored else 'no ':<8} {note}")

    print("\nKILL CRITERION 1 -- a minimal usable feature extractor must be "
          "writable in under ~250 B of golfed numpy.")
    print(f"{'extractor':<16}{'cost over null':>16}   verdict")
    for name, note, size, d, dt, stored, delta, wb, sb in rows:
        if name == "null":
            continue
        print(f"{name:<16}{delta:>+16,}   "
              f"{'under 250 B' if delta < 250 else 'FIRES -- over 250 B'}")
    usable = [r for r in rows if r[0] != "null" and not r[5]]
    best = min(usable, key=lambda r: r[6])
    print(f"\ncheapest non-null extractor with no stored coefficients: "
          f"{best[0]} at {best[6]:+} B over the null artifact "
          f"({best[2].description_length} B as a complete artifact)")
    fired = [r[0] for r in rows if r[0] != "null" and r[6] >= 250]
    print(f"rows that DO fire the criterion: {fired or 'none'}")
    if not fired:
        raise SystemExit(
            "no row fires the criterion, so this table has not been shown "
            "capable of a negative -- add an expensive control before trusting it")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
