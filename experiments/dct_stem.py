# pi/(2p) for p = 8 and p = 4, written as short literals rather than as
# np.pi/16 (which is two bytes longer and one more name to resolve).
_C8, _C4 = ".19634954", ".39269908"


def _dct_pre(p: int, k: int) -> str:
    c = _C8 if p == 8 else _C4
    return f"D=np.cos(np.outer(np.arange({p})*2+1,np.arange({k}))*{c})\n"


def _blocks(p: int) -> str:
    """Reshape+transpose that puts the two intra-block axes last.

    `x` is uint8; every consumer below is a matmul, a mean or an FFT, all of
    which promote it. Casting first would cost 22 source bytes and buy nothing.
    """
    g = 32 // p
    return f"x.reshape(-1,{g},{p},{g},{p},3).transpose(0,1,3,5,2,4)"


def _grid(p: int) -> str:
    """The same blocks with no transpose at all, for transforms that can be
    told which axes to work on. `np.fft.rfft2(., axes=(2,4))` is ten bytes
    shorter than transposing the axes into place, and copies nothing."""
    g = 32 // p
    return f"x.reshape(-1,{g},{p},{g},{p},3)"


def _dct(p: int, k: int) -> tuple[str, str, int]:
    g = 32 // p
    return (_dct_pre(p, k),
            f"(D.T@{_blocks(p)}@D).reshape(len(x),-1)",
            g * g * 3 * k * k)


def _dct_abs(p: int, k: int) -> tuple[str, str, int]:
    g = 32 // p
    return (_dct_pre(p, k),
            f"abs(D.T@{_blocks(p)}@D).reshape(len(x),-1)",
            g * g * 3 * k * k)


def _had(p: int, k: int, rect: bool = False) -> tuple[str, str, int]:
    """Walsh-Hadamard over p x p blocks, keeping the k x k lowest *sequency*.

    Natural Hadamard order is not sequency order: column 1 of H8 is the highest
    sequency, not the lowest. The column pick below reorders to sequency, which
    is what makes "keep the low ones" mean the same thing it means for the DCT.
    """
    g = 32 // p
    if p == 8:
        pick = {1: "[:,:1]", 2: "[:,::4]", 3: "[:,[0,4,6]]", 4: "[:,[0,4,6,2]]"}[k]
        pre = f"H=np.array([[1.,1],[1,-1]]);H=np.kron(H,np.kron(H,H)){pick}\n"
    else:
        pick = {1: "[:,:1]", 2: "[:,::2]", 3: "[:,[0,2,3]]", 4: ""}[k]
        pre = f"H=np.array([[1.,1],[1,-1]]);H=np.kron(H,H){pick}\n"
    body = f"H.T@{_blocks(p)}@H"
    body = f"abs({body})" if rect else f"({body})"
    return pre, f"{body}.reshape(len(x),-1)", g * g * 3 * k * k


def _had_abs(p: int, k: int) -> tuple[str, str, int]:
    return _had(p, k, rect=True)


def _fftlog(p: int, k: int) -> tuple[str, str, int]:
    g = 32 // p
    return ("",
            f"np.log1p(abs(np.fft.rfft2({_grid(p)},axes=(2,4))"
            f"[:,:,:{k},:,:{k}])).reshape(len(x),-1)",
            g * g * 3 * k * k)


def _fftabs(p: int, k: int) -> tuple[str, str, int]:
    g = 32 // p
    return ("",
            f"abs(np.fft.rfft2({_grid(p)},axes=(2,4))[:,:,:{k},:,:{k}])"
            f".reshape(len(x),-1)",
            g * g * 3 * k * k)


def _dct_fft(p: int, k: int) -> tuple[str, str, int]:
    """The same truncated DCT magnitude, routed through np.fft instead of a
    generated cosine matrix — to price the two ways of getting there."""
    g = 32 // p
    return ("",
            f"abs(np.fft.rfft2({_blocks(p)},({2 * p},{2 * p}))[...,:{k},:{k}])"
            f".reshape(len(x),-1)",
            g * g * 3 * k * k)


def _mean(g: int) -> tuple[str, str, int]:
    s = 32 // g
    return ("", f"x.reshape(-1,{g},{s},{g},{s},3).mean((2,4)).reshape(len(x),-1)",
            g * g * 3)


def _mean_rect(g: int) -> tuple[str, str, int]:
    """Block means, rectified about the image mean — a nonlinearity with no
    transform under it. This is the control that separates "the transform
    helps" from "any nonlinearity helps"."""
    s = 32 // g
    pre = (f"def m(y):\n"
           f" v=y.reshape(-1,{g},{s},{g},{s},3).mean((2,4))\n"
           f" return abs(v-v.mean((1,2,3),keepdims=True)).reshape(len(v),-1)\n")
    return pre, "m(x)", g * g * 3


STEMS: dict[str, tuple[str, str, int]] = {
    # --- the free-input incumbents -------------------------------------
    "rgb8": _mean(8),          # 192 — the current free-input baseline
    "rgb4": _mean(4),          # 48
    "rgb16": _mean(16),        # 768
    "rgb8r": _mean_rect(8),    # 192 — rectified block means, no transform
    "rgb16r": _mean_rect(16),  # 768
    # --- generated orthogonal transforms, truncated ---------------------
    "dct8k1": _dct(8, 1),      # 48   (== the 4x4 block mean, up to scale)
    "dct8k2": _dct(8, 2),      # 192  <- dimension-matched to rgb8
    "dct8k3": _dct(8, 3),      # 432
    "dct8k4": _dct(8, 4),      # 768
    "dct4k2": _dct(4, 2),      # 768
    "had8k2": _had(8, 2),      # 192  <- trig-free, dimension-matched to rgb8
    "had8k4": _had(8, 4),      # 768
    "had4k2": _had(4, 2),      # 768
    # --- generated, plus a nonlinearity the head cannot undo -------------
    "dctabs8k2": _dct_abs(8, 2),   # 192
    "dctabs8k3": _dct_abs(8, 3),   # 432
    "dctabs8k4": _dct_abs(8, 4),   # 768
    "dctabs4k2": _dct_abs(4, 2),   # 768
    "hadabs8k2": _had_abs(8, 2),   # 192  <- trig-free *and* nonlinear
    "hadabs8k4": _had_abs(8, 4),   # 768
    "fftlog8k2": _fftlog(8, 2),    # 192
    "fftlog8k3": _fftlog(8, 3),    # 432
    "fftabs8k2": _fftabs(8, 2),    # 192
    "fftabs8k3": _fftabs(8, 3),    # 432
    "fftabs8k4": _fftabs(8, 4),    # 768
    "fftabs4k2": _fftabs(4, 2),    # 768
    "fftabs16k2": _fftabs(16, 2),  # 48
    "dctfft8k2": _dct_fft(8, 2),   # 192, via np.fft rather than a cos matrix
}

# The stored-basis controls. `w` carries a real basis matrix, which is exactly
# what lever C says should not be necessary. Built at run time from the fit
# split, so the shipped bytes are a genuine learned basis.
STORED = {
    #  name       patch  rank  int8?
    "pw4r3": (4, 3, False),     # 8x8 grid x 3 comps = 192 dims, matched to rgb8
    "pw4r3q": (4, 3, True),     # the same basis at int8 — item 8's "~144 B"
    "pw4r1": (4, 1, False),     # 64 dims
    "pw2r3": (2, 3, False),     # 16x16 grid x 3 comps = 768 dims
}


def stored_expr(patch: int, rank: int, i8: bool) -> tuple[str, str, int]:
    g, n = 32 // patch, patch * patch * 3 * rank
    if i8:
        pre = (f"M=np.frombuffer(B,np.int8,{n},{{OFF}})"
               f".astype(np.float32).reshape(-1,{rank})*{{SCALE}}\n")
    else:
        pre = (f"M=np.frombuffer(B,np.float16,{n},{{OFF}})"
               f".astype(np.float32).reshape(-1,{rank})\n")
    expr = (f"(x.reshape(-1,{g},{patch},{g},{patch},3).transpose(0,1,3,2,4,5)"
            f".reshape(len(x),{g * g},-1)@M).reshape(len(x),-1)")
    return pre, expr, g * g * rank


def fit_basis(xfit: np.ndarray, patch: int, rank: int, i8: bool = False):
    """PCA-whitening basis over patch x patch x 3 tiles, truncated to `rank`.

    Returns (bytes, scale). This is the shipped-basis control: exactly the
    object lever C claims not to need.
    """
    g = 32 // patch
    p = (xfit[:5000].astype(np.float32)
         .reshape(-1, g, patch, g, patch, 3).transpose(0, 1, 3, 2, 4, 5)
         .reshape(-1, patch * patch * 3))
    p = p - p.mean(0)
    c = np.cov(p, rowvar=False)
    w, v = np.linalg.eigh(c)
    o = np.argsort(w)[::-1][:rank]
    M = (v[:, o] / np.sqrt(w[o] + 1e-3)).astype(np.float32)
    if not i8:
        return M.astype(np.float16).tobytes(), 1.0
    s = float(np.abs(M).max()) / 127
    return np.rint(M / s).astype(np.int8).tobytes(), s


