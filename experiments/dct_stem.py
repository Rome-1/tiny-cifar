# --------------------------------------------------------------------------
# the stems
#
# Each is (prelude, expression, dim). `x` is uint8 [N,32,32,3] exactly as the
# harness hands it over; the expression must bind to a float matrix [N, dim].
# Written as it would ship.
#
# Preludes run once at import: a generated basis costs its source and nothing
# else, which is the entire point of the exercise.
