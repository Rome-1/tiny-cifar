def run_final(a) -> int:
    xfit, yfit, xval, yval = load_dev()
    for spec in a.names:
        name, bits, lam = spec.split(":")
        bits, lam = int(bits), float(lam)
        dim = _local_dim(name, xval[:8], xfit)
        t0 = time.perf_counter()
        G, Hy = gram(name, xfit, yfit, dim, xfit)
        G.flat[:: dim + 2] += lam
        W = np.linalg.solve(G, Hy)
        train_s = time.perf_counter() - t0
        files, Wq = head_files(name, W, bits, xfit)
        aname = f"lt-{name}-{bits}b"
        d = emit(aname, files)
        rv = evaluate(d, name=aname, split="val", save=False,
                      method=f"linear head on the {name} stem, {bits}-bit codebook")
        print(f"  val    {summarize(rv)}")
        rt = evaluate(
            d, name=aname, split="test", train_seconds=train_s,
            method=f"ridge head on the {name} stem, {bits}-bit global codebook",
            notes=f"stem generated in source, nothing stored; dim {dim}, "
                  f"lambda={lam:g}; selected on val")
        print(f"  TEST   {summarize(rt)}")
    return 0


def run_mdl(a) -> int:
    """Price each declared point on the second scoreboard.

    Same convention as `experiments/mdl_audit.py`, whose helpers this imports
    rather than reimplements: cross-entropy on the *quantized* weights actually
    shipped, temperature fitted on the fit split (the decoder holds it too, so
    it can repeat the fit), against the 4,152 B cost of sending the 10,000 test
    labels with no model at all.
    """
    from experiments.mdl_audit import (
        UNIFORM, artifact_bytes, cross_entropy_bits, fit_temperature,
    )
    from tinycifar.data import load

    xfit, yfit, xval, yval = load_dev()
    _, _, xte, yte = load()
    print(f"baseline: {UNIFORM:,.0f} B to send 10,000 labels with no model\n")
    print(f"{'artifact':<20}{'bytes':>7}{'test':>8}{'bits/lab':>10}"
          f"{'labels':>8}{'total':>8}  verdict")
    for spec in a.names:
        name, bits, lam = spec.split(":")
        bits, lam = int(bits), float(lam)
        dim = _local_dim(name, xval[:8], xfit)
        G, Hy = gram(name, xfit, yfit, dim, xfit)
        G.flat[:: dim + 2] += lam
        W = np.linalg.solve(G, Hy)
        _, Wq = head_files(name, W, bits, xfit)

        def logits(x, Wq=Wq, name=name, xfit=xfit):
            return np.concatenate([
                _featurize(name, x[i:i + 5000], xfit) @ Wq[:-1] + Wq[-1]
                for i in range(0, len(x), 5000)])

        temp, _ = fit_temperature(logits(xfit), yfit)
        bpl = cross_entropy_bits(logits(xte), yte, temp)
        aname = f"lt-{name}-{bits}b"
        nb = artifact_bytes(aname)
        if nb is None:
            raise SystemExit(f"{aname}: run `final` first so it has a size")
        lab = 10000 * bpl / 8
        tot = nb + lab
        print(f"{aname:<20}{nb:>7,}"
              f"{100 * float((logits(xte).argmax(1) == yte).mean()):>7.2f}%"
              f"{bpl:>10.3f}{lab:>8,.0f}{tot:>8,.0f}  "
              f"{'pays, ' if tot < UNIFORM else 'costs '}"
              f"{abs(tot - UNIFORM):,.0f} B")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("cost")
    s = sub.add_parser("sweep")
    s.add_argument("--stems", nargs="*")
    s.add_argument("--bits", nargs="*", type=int, default=[1, 2, 3, 4, 5, 6])
    # Wide and dense on purpose. Stems differ in feature scale by up to 8x
    # (an 8x8 DCT's DC term is 8x a block mean), and the effective ridge
    # penalty goes as the square of that. A coarse grid tunes one arm better
    # than another and the difference reads as a transform effect.
    s.add_argument("--lam", nargs="*", type=float,
                   default=[10.0 ** e for e in range(0, 15)])
    s.add_argument("--ceiling", type=int, default=2200)
    f = sub.add_parser("final")
    f.add_argument("--names", nargs="+", help="stem:bits:lam")
    g = sub.add_parser("golf")
    g.add_argument("--names", nargs="+", help="stem:bits:lam")
    m = sub.add_parser("mdl")
    m.add_argument("--names", nargs="+", help="stem:bits:lam")
    a = ap.parse_args(argv)
    a.bands = [(300, 500), (500, 700), (700, 1000), (1000, 1500), (1500, 2200)]
    if a.cmd == "cost":
        return run_cost(a)
    if a.cmd == "sweep":
        return run_sweep(a)
    if a.cmd == "golf":
        return run_golf(a)
    if a.cmd == "mdl":
        return run_mdl(a)
    return run_final(a)


if __name__ == "__main__":
    raise SystemExit(main())
