COST_TEMPLATE = """import numpy as np
{PRE}def predict(x):
 return ({EXPR}).argmax(1)%10
"""

COST_TEMPLATE_STORED = """import numpy as np
B=open(__file__[:-10]+"w","rb").read()
{PRE}def predict(x):
 return ({EXPR}).argmax(1)%10
"""

NULL = """import numpy as np
def predict(x):
 return (x[:,0,0]*1.).argmax(1)%10
"""


def cost_files(name: str, xfit=None) -> tuple[dict[str, bytes], int]:
    if name == "null":
        return {"predict.py": NULL.encode()}, 3
    if name in STORED:
        blob, scale = basis(name, xfit)
        pre, expr, dim = stored_expr(*STORED[name])
        src = COST_TEMPLATE_STORED.format(
            PRE=pre.format(OFF=0, SCALE=f"{scale:.6g}"), EXPR=expr)
        return {"predict.py": src.encode(), "w": blob}, dim
    pre, expr, dim = STEMS[name]
    return {"predict.py": COST_TEMPLATE.format(PRE=pre, EXPR=expr).encode()}, dim


def run_cost(argv) -> int:
    xfit, yfit, xval, yval = load_dev()
    names = ["null"] + list(STEMS) + list(STORED)
    rows = []
    null_b = None
    for name in names:
        files, dim = cost_files(name, xfit)
        viol = A.check_imports(files)
        if viol:
            raise RuntimeError(f"{name}: {viol}")
        size = A.measure(files)
        # Run it: a fragment that does not execute may not post a byte count.
        with tempfile.TemporaryDirectory() as td:
            A.write_dir(files, Path(td))
            rec = evaluate(td, name=f"stem-{name}", split="val", save=False)
        if rec["description_length"] != size.description_length:
            raise RuntimeError(f"{name}: size disagreement")
        d = _local_dim(name, xval[:8], xfit)
        if d != dim:
            raise RuntimeError(f"{name}: expected {dim} dims, produced {d}")
        if null_b is None:
            null_b = size.description_length
        rows.append((name, size, dim, name in STORED,
                     size.description_length - null_b,
                     len(files.get("w", b"")), len(files["predict.py"])))

    print(f"\n{'stem':<12}{'bytes':>7}{'delta':>7}{'src B':>7}{'coef B':>8}"
          f"{'dims':>6}  stored?")
    print("-" * 56)
    for name, size, dim, stored, delta, wb, sb in rows:
        print(f"{name:<12}{size.description_length:>7,}{delta:>+7,}{sb:>7}"
              f"{wb:>8,}{dim:>6}  {'YES' if stored else 'no'}")

    gen = [r for r in rows if r[0] != "null" and not r[3]]
    cheapest = min(gen, key=lambda r: r[4])
    print(f"\ncheapest generated stem: {cheapest[0]} at {cheapest[4]:+} B over null")
    fired = [r[0] for r in rows if r[0] != "null" and r[4] >= 150]
    print(f"rows costing >= 150 B over null: {fired or 'none'}")
    if not fired:
        raise SystemExit(
            "no row is expensive, so this table has not been shown capable of a "
            "negative — add a stored-basis control before trusting it")
    return 0


def _local_dim(name: str, x: np.ndarray, xfit) -> int:
    if name == "null":
        return 3
    return _featurize(name, x, xfit).shape[1]


