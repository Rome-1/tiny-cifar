"""Does a generated-not-stored input transform buy accuracy per byte on CIFAR-10?

Lever C in [what-to-try.md](../docs/what-to-try.md) says anything a line of numpy
generates costs nothing, because the artifact ships source rather than data. The
Speech Commands de-risk ([kws-derisk.md](../docs/kws-derisk.md)) put a number on
how large that can get: a complete log-mel front end cost **99 B** and stored
nothing, where shipping the equivalent filterbank as weights cost **1,119 B**.
`what-to-try.md` item 8 names a "zero-byte analytic DCT stem" as untested on
CIFAR-10. This module tests it.

Two phases, and the first is the one the KWS work showed matters:

``cost``
    Measure each candidate transform **on its own**, as a complete runnable
    artifact whose classifier is deliberately degenerate (``v.argmax(1)%10``).
    That is the DSP floor: what the stem costs before a single weight ships.
    ``delta`` subtracts the ``null`` row — the same artifact with the transform
    removed — so the number isolates the transform from the fixed cost of being
    a Python artifact. Every row runs through the harness sandbox, so a fragment
    that does not execute cannot post a byte count.

``sweep``
    Put an identical quantized ridge head on each stem and compare at matched
    description length, selecting on ``data.load_dev()``'s validation split.

One thing to state before reading any of it, because it bounds what a transform
can possibly buy here. **An orthogonal transform in front of a linear head is a
no-op.** DCT, Hadamard and a whitening rotation are all invertible linear maps,
so the head can undo them exactly; the accuracy is identical to the accuracy on
raw pixels. A transform can therefore only earn its bytes two ways:

  * **truncation** — keeping the K lowest-frequency coefficients per block is a
    *different subspace* than the block mean, and might be a better one at equal
    dimension;
  * **a nonlinearity** — ``abs`` or ``log1p(abs(.))`` of the coefficients is not
    something the head can undo, which is where the conv family's gains live.

Both are represented below. So is the control that decides the lever-C question:
a patch-whitening basis of the same shape, **shipped as bytes** instead of
generated by a formula.

Flip TTA is deliberately absent from every arm. With a linear head over a linear
stem, averaging the features of an image and its mirror is exactly classifying
the horizontally symmetrized image, which destroys every antisymmetric
coefficient — and for a block-DCT that is half of them. It would penalize the
DCT arms for a reason that has nothing to do with the transform.

Two more subcommands exist for the points the sweep selects. ``golf`` emits each
one twice — golfed and not — over identical weights and prices both, because this
repo has a recorded case where golfing cut raw bytes and *added* xz bytes.
``final`` scores a point once on test. ``mdl`` prices it on the second scoreboard.

Run:
    python3 experiments/dct_stem.py cost
    python3 experiments/dct_stem.py sweep
    python3 experiments/dct_stem.py golf  --names <stem>:<bits>:<lam> ...
    python3 experiments/dct_stem.py final --names <stem>:<bits>:<lam> ...
    python3 experiments/dct_stem.py mdl   --names <stem>:<bits>:<lam> ...
"""

